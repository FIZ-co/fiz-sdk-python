"""Checks every ```python block of README.md as written: cuts each into
tests/readme/block_<n>.py, compiles it, and type-checks them all with mypy in strict mode.

A block that continues an earlier one (uses `fiz`, `invoice_id`, …) gets declarations for
those names only; nothing else is added or changed.
"""

from __future__ import annotations

import ast
import re
import shutil
import sys
from pathlib import Path

from mypy import api as mypy

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "readme"

# Names README fragments take from the blocks before them.
AMBIENT = {
    "Fiz": "from fiz_sdk import Fiz",
    "fiz": "from fiz_sdk import Fiz\n\nfiz: Fiz",
    "invoice_id": "invoice_id: str",
    "draft": "from fiz_sdk.types import CreateInvoiceDto\n\ndraft: CreateInvoiceDto",
    "order": "class _Order:\n    id: str\n\n\norder: _Order",
    "access_token": "access_token: str",
}


def borrowed(code: str) -> list[str]:
    """The ambient names a block reads without binding them itself."""
    tree = ast.parse(code)
    bound: set[str] = set()
    read: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            (bound if isinstance(node.ctx, ast.Store) else read).add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            bound.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update((alias.asname or alias.name).split(".")[0] for alias in node.names)
    return [name for name in AMBIENT if name in read and name not in bound]


def main() -> int:
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    blocks = list(re.finditer(r"```python\n(.*?)```", readme, re.DOTALL))
    for index, match in enumerate(blocks):
        code = match.group(1)
        line = readme.count("\n", 0, match.start()) + 2
        try:
            compile(code, f"README.md line {line}", "exec")
        except SyntaxError as error:
            print(f"README.md block at line {line}: {error}", file=sys.stderr)
            return 1
        prelude = [f"# README.md line {line}. Generated by scripts/check_readme.py; do not edit."]
        prelude += [AMBIENT[name] for name in borrowed(code)]
        (OUT / f"block_{index}.py").write_text("\n".join(prelude) + "\n\n" + code, encoding="utf-8")
    files = sorted(str(path) for path in OUT.glob("block_*.py"))
    out, err, status = mypy.run(["--strict", "--python-version", "3.10", *files])
    sys.stdout.write(out)
    sys.stderr.write(err)
    if status == 0:
        print(f"README: {len(blocks)} Python blocks compile and type-check")
    return status


if __name__ == "__main__":
    sys.exit(main())
