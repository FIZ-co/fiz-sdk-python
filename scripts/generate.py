"""Generates src/fiz_sdk/generated/ from openapi/openapi.json. No network access:
`uv run python scripts/update_spec.py` refreshes the spec first.

- schemas.py     a TypedDict per schema of the API document (an inline object
                 gets its own, named after where it appears), and one per
                 operation for its query parameters (`<OperationId>Query`).
                 What a request sends (bodies, queries) has ReadOnly keys: the
                 SDK never changes them, and a response can then be sent back
                 as a request where the API allows it (a template export).
- operations.py  operationId → method, path, and whether the route takes an
                 Idempotency-Key. The client reads this table, so a method
                 never restates its route by hand.
- calls.py       the overloads that type `call()` for every operation

The output is formatted with the pinned ruff, so regenerating gives the same
bytes (CI regenerates and diffs).
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / "openapi" / "openapi.json"
OUT = ROOT / "src" / "fiz_sdk" / "generated"
HEADER = "# Generated by scripts/generate.py from openapi/openapi.json. Do not edit.\n"
METHODS = ("get", "post", "put", "patch", "delete")
REF_PREFIX = "#/components/schemas/"
SCALARS = {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}
LINE = 100

Json = dict[str, Any]


@dataclass
class Field:
    name: str
    annotation: str
    required: bool
    doc: str | None
    deps: set[str]


@dataclass
class Definition:
    name: str
    doc: str | None
    fields: list[Field] = field(default_factory=list)
    read_only: bool = False

    @property
    def deps(self) -> set[str]:
        return {dep for f in self.fields for dep in f.deps}


@dataclass
class Operation:
    operation_id: str
    method: str
    path: str
    idempotent: bool
    has_path_params: bool
    query: str | None
    query_required: bool
    body: str | None
    body_required: bool
    response: str


def pascal(text: str) -> str:
    """`byRate` → `ByRate`, `InvoicesController_findAll` → `InvoicesControllerFindAll`."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", text))


def literal(value: Any) -> str:
    if isinstance(value, bool):
        return repr(value)
    if isinstance(value, (str, int)):
        return json.dumps(value, ensure_ascii=False)
    raise ValueError(f"Unsupported enum value {value!r}")


def union(alternatives: list[str]) -> str:
    unique = list(dict.fromkeys(alternatives))
    if "None" in unique:
        unique = [a for a in unique if a != "None"] + ["None"]
    return " | ".join(unique)


def doc_of(schema: Json) -> str | None:
    parts = [schema["description"].strip()] if schema.get("description") else []
    if schema.get("deprecated"):
        parts.append("Deprecated.")
    return "\n\n".join(parts) or None


class Builder:
    """Turns schemas into TypedDict definitions and type expressions."""

    def __init__(self, schemas: dict[str, Json]) -> None:
        self.schemas = schemas
        self.definitions: dict[str, Definition] = {}

    def typed_dict(
        self, name: str, doc: str | None, properties: list[tuple[str, Json, bool, bool]]
    ) -> str:
        """`properties`: (name, schema, required, accepts None as "not given")."""
        if name in self.definitions:
            raise ValueError(f"Two types would be named {name}")
        definition = Definition(name, doc)
        self.definitions[name] = definition
        for prop, schema, required, none_allowed in properties:
            deps: set[str] = set()
            alternatives = self.alternatives(schema, name + pascal(prop), deps)
            if none_allowed:
                alternatives.append("None")
            definition.fields.append(
                Field(prop, union(alternatives), required, doc_of(schema), deps)
            )
        return name

    def schema_typed_dict(self, name: str, schema: Json) -> str:
        required = set(schema.get("required", []))
        properties = [(p, s, p in required, False) for p, s in schema.get("properties", {}).items()]
        return self.typed_dict(name, doc_of(schema), properties)

    def annotation(self, schema: Json, hint: str, deps: set[str]) -> str:
        return union(self.alternatives(schema, hint, deps))

    def alternatives(self, schema: Json, hint: str, deps: set[str]) -> list[str]:
        """The type of `schema` as union members; `hint` names an inline object."""
        result: list[str]
        if "$ref" in schema:
            ref = schema["$ref"]
            if not ref.startswith(REF_PREFIX) or ref[len(REF_PREFIX) :] not in self.schemas:
                raise ValueError(f"{hint}: unsupported $ref {ref}")
            target = ref[len(REF_PREFIX) :]
            deps.add(target)
            result = [target]
        elif "allOf" in schema:
            if len(schema["allOf"]) != 1:
                raise ValueError(f"{hint}: allOf with several schemas is not supported")
            result = self.alternatives(schema["allOf"][0], hint, deps)
        elif "oneOf" in schema or "anyOf" in schema:
            options = schema.get("oneOf") or schema["anyOf"]
            result = []
            for index, option in enumerate(options):
                result += self.alternatives(option, f"{hint}Option{index + 1}", deps)
        elif "enum" in schema:
            values = schema["enum"]
            literals = [literal(v) for v in values if v is not None]
            result = [f"Literal[{', '.join(literals)}]"] if literals else []
            if None in values:
                result.append("None")
        else:
            kind = schema.get("type")
            if kind in SCALARS:
                result = [SCALARS[kind]]
            elif kind == "array":
                result = [f"list[{self.annotation(schema.get('items', {}), hint + 'Item', deps)}]"]
            elif kind == "object" or "properties" in schema:
                extra = schema.get("additionalProperties")
                if schema.get("properties"):
                    deps.add(self.schema_typed_dict(hint, schema))
                    result = [hint]
                elif isinstance(extra, dict):
                    result = [f"dict[str, {self.annotation(extra, hint + 'Value', deps)}]"]
                else:
                    result = ["dict[str, Any]"]
            elif kind is None:
                result = ["Any"]
            else:
                raise ValueError(f"{hint}: unsupported type {kind!r}")
        if schema.get("nullable"):
            result.append("None")
        return result


def docstring(text: str, indent: int) -> list[str]:
    pad = " " * indent
    lines: list[str] = []
    for source_line in text.splitlines():
        lines += textwrap.wrap(
            source_line, width=LINE - indent - 6, break_long_words=False, break_on_hyphens=False
        ) or [""]
    lines = [line.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') for line in lines]
    if lines[-1].endswith('"'):
        lines[-1] = lines[-1][:-1] + '\\"'
    if len(lines) == 1:
        return [f'{pad}"""{lines[0]}"""']
    return [
        f'{pad}"""{lines[0]}',
        *[f"{pad}{line}" if line else "" for line in lines[1:]],
        f'{pad}"""',
    ]


def render_definition(definition: Definition, defined: set[str]) -> list[str]:
    def annotation(f: Field) -> str:
        # A type not defined yet (a cycle, or the class itself) is quoted.
        text = json.dumps(f.annotation) if f.deps - defined else f.annotation
        if definition.read_only:
            text = f"ReadOnly[{text}]"
        return text if f.required else f"NotRequired[{text}]"

    if any(not f.name.isidentifier() or keyword.iskeyword(f.name) for f in definition.fields):
        lines = [f"{definition.name} = TypedDict(", f"    {json.dumps(definition.name)},", "    {"]
        lines += [f"        {json.dumps(f.name)}: {annotation(f)}," for f in definition.fields]
        lines += ["    },", ")"]
        if definition.doc:
            lines += docstring(definition.doc, 0)
        return lines

    lines = [f"class {definition.name}(TypedDict):"]
    if definition.doc:
        lines += docstring(definition.doc, 4)
        if definition.fields:
            lines.append("")
    for f in definition.fields:
        lines.append(f"    {f.name}: {annotation(f)}")
        if f.doc:
            lines += docstring(f.doc, 4)
    if not definition.doc and not definition.fields:
        lines.append("    pass")
    return lines


def ordered(definitions: dict[str, Definition]) -> list[str]:
    """Every type after the types it uses, where there is no cycle; else by name."""
    order: list[str] = []
    done: set[str] = set()
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in done or name in visiting:
            return
        visiting.add(name)
        for dep in sorted(definitions[name].deps):
            visit(dep)
        visiting.discard(name)
        done.add(name)
        order.append(name)

    for name in sorted(definitions):
        visit(name)
    return order


def build(spec: Json) -> tuple[Builder, list[Operation]]:
    schemas: dict[str, Json] = spec["components"]["schemas"]
    builder = Builder(schemas)
    for name in sorted(schemas):
        if not name.isidentifier():
            raise ValueError(f"Schema name {name!r} is not a Python identifier")
        builder.schema_typed_dict(name, schemas[name])

    operations: list[Operation] = []
    sent: set[str] = set()
    received: set[str] = set()
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            operation_id = op.get("operationId")
            if not operation_id:
                raise ValueError(f"{method} {path} has no operationId")
            base = pascal(operation_id)
            parameters = op.get("parameters", [])
            query_params = [p for p in parameters if p["in"] == "query"]
            query = None
            if query_params:
                query = builder.typed_dict(
                    base + "Query",
                    f"Query parameters of {method.upper()} {path}.",
                    [
                        (
                            p["name"],
                            {**p["schema"], "description": p.get("description")},
                            bool(p.get("required")),
                            not p.get("required"),
                        )
                        for p in query_params
                    ],
                )
                sent.add(query)
            body = None
            request_body = op.get("requestBody")
            if request_body:
                body_schema = request_body["content"]["application/json"]["schema"]
                body = builder.annotation(body_schema, base + "Body", sent)
            response = "Any"
            for status in ("200", "201"):
                content = op.get("responses", {}).get(status, {}).get("content", {})
                if "application/json" in content:
                    response = builder.annotation(
                        content["application/json"]["schema"], base + "Response", received
                    )
                    break
            operations.append(
                Operation(
                    operation_id=operation_id,
                    method=method.upper(),
                    path=path,
                    idempotent=any(
                        p["in"] == "header" and p["name"].lower() == "idempotency-key"
                        for p in parameters
                    ),
                    has_path_params=any(p["in"] == "path" for p in parameters),
                    query=query,
                    query_required=any(p.get("required") for p in query_params),
                    body=body,
                    body_required=bool(request_body and request_body.get("required")),
                    response=response,
                )
            )
    operations.sort(key=lambda o: o.operation_id)
    # Only what requests alone use: a type responses use too stays writable.
    for name in closure(builder.definitions, sent) - closure(builder.definitions, received):
        builder.definitions[name].read_only = True
    return builder, operations


def closure(definitions: dict[str, Definition], roots: set[str]) -> set[str]:
    """`roots` and every type they use, directly or not."""
    found: set[str] = set()
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name not in found:
            found.add(name)
            pending += definitions[name].deps
    return found


def render_schemas(builder: Builder) -> str:
    lines = [
        HEADER,
        '"""Every schema of the API document as a TypedDict, and the query parameters',
        'of each operation (`<OperationId>Query`)."""',
        "",
        "from typing import Any, Literal",
        "",
        "from .._compat import NotRequired, ReadOnly, TypedDict",
        "",
    ]
    names = ordered(builder.definitions)
    lines += ["__all__ = [", *[f"    {json.dumps(n)}," for n in sorted(names)], "]", ""]
    defined: set[str] = set()
    for name in names:
        lines += ["", *render_definition(builder.definitions[name], defined), ""]
        defined.add(name)
    return "\n".join(lines) + "\n"


def render_operations(spec: Json, operations: list[Operation]) -> str:
    lines = [
        HEADER,
        '"""Every operation of the API document: the client reads this table."""',
        "",
        "from collections.abc import Mapping",
        "from typing import Final, Literal, NamedTuple",
        "",
        f"API_VERSION: Final = {json.dumps(spec['info']['version'])}",
        '"""`info.version` of the API document this SDK was generated from."""',
        "",
        "",
        "class Operation(NamedTuple):",
        "    method: str",
        '    """`GET`, `POST`, `PUT`, `PATCH` or `DELETE`."""',
        "    path: str",
        '    """The route as documented, e.g. `/invoices/{id}/issue`."""',
        "    idempotent: bool",
        '    """Whether the route takes an `Idempotency-Key` header."""',
        "",
        "",
        "OperationId = Literal[",
        *[f"    {json.dumps(o.operation_id)}," for o in operations],
        "]",
        "",
        "OPERATIONS: Final[Mapping[str, Operation]] = {",
        *[
            f"    {json.dumps(o.operation_id)}: "
            f"Operation({json.dumps(o.method)}, {json.dumps(o.path)}, {o.idempotent}),"
            for o in operations
        ],
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_calls(operations: list[Operation]) -> str:
    used: set[str] = set()
    for o in operations:
        for annotation in (o.query, o.body, o.response):
            if annotation:
                used |= set(re.findall(r"\b[A-Z]\w*\b", annotation))
    imported = sorted(used - {"Any", "Literal", "None"})
    lines = [
        HEADER,
        '"""`call()` typed for every operation of the API document."""',
        "",
        "from collections.abc import Mapping",
        "from typing import Any, Literal, overload",
        "",
        "from .._compat import Unpack",
        "from ..options import RequestOptions",
        "from .schemas import (",
        *[f"    {name}," for name in imported],
        ")",
        "",
        "",
        "class TypedCalls:",
        '    """Types `call()` with each operation\'s parameters, body and response."""',
    ]
    for o in operations:
        params = ["        self,", f"        operation_id: Literal[{json.dumps(o.operation_id)}],"]
        keyword_only: list[str] = []
        if o.has_path_params:
            keyword_only.append("        path: Mapping[str, str],")
        if o.query:
            keyword_only.append(
                f"        query: {o.query},"
                if o.query_required
                else f"        query: {o.query} | None = None,"
            )
        if o.body:
            keyword_only.append(
                f"        body: {o.body},"
                if o.body_required
                else f"        body: {o.body} | None = None,"
            )
        if keyword_only:
            params += ["        *,", *keyword_only]
        params.append("        **options: Unpack[RequestOptions],")
        lines += ["", "    @overload", "    def call(", *params, f"    ) -> {o.response}: ..."]
    lines += [
        "",
        "    def call(",
        "        self,",
        "        operation_id: str,",
        "        *,",
        "        path: Mapping[str, str] | None = None,",
        "        query: Mapping[str, Any] | None = None,",
        "        body: Any = None,",
        "        **options: Unpack[RequestOptions],",
        "    ) -> Any:",
        '        """Calls any API operation by its OpenAPI `operationId`. Resource methods use',
        "        this; call it directly for an operation this SDK version does not wrap yet.",
        '        """',
        "        return self._call(operation_id, path, query, body, options)",
        "",
        "    def _call(",
        "        self,",
        "        operation_id: str,",
        "        path: Mapping[str, str] | None,",
        "        query: Mapping[str, Any] | None,",
        "        body: Any,",
        "        options: RequestOptions,",
        "    ) -> Any:",
        "        raise NotImplementedError",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    builder, operations = build(spec)
    files = {
        OUT / "__init__.py": HEADER + '"""Code generated from openapi/openapi.json."""\n',
        OUT / "schemas.py": render_schemas(builder),
        OUT / "operations.py": render_operations(spec, operations),
        OUT / "calls.py": render_calls(operations),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    paths = [str(p) for p in files]
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--quiet", "--fix", "--select", "I", *paths],
        check=True,
    )
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", *paths], check=True)
    print(f"Generated {len(operations)} operations and {len(builder.definitions)} types")


if __name__ == "__main__":
    main()
